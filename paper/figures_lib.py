def positions(run: str, sub: str = "seed0") -> np.ndarray | None:
    """Final-round pair positions, ordered by pair index, shape (n_pairs, L)."""
    path = RESULTS / run / sub / "history.json"
    if not path.exists():
        return None
    entry = json.loads(path.read_text())[-1]["pair_positions"]
    keys = sorted(entry, key=lambda s: int(s.split("-")[1]))
    return np.array([entry[k] for k in keys])


def mean_radius(pos: np.ndarray) -> float:
    """Mean distance of the pair positions from their own centroid."""
    return float(np.mean(np.linalg.norm(pos - pos.mean(axis=0), axis=1)))


def intra_inter(run: str, sub: str = "seed0", rnd: int = FINAL_ROUND):
    """Mean NLL on the axis a pair owns, and on the six it does not.

    Ownership is the one-to-one assignment of pairs to benchmarks that minimises
    total NLL, so the split does not assume the intended pairing held.
    """
    path = RESULTS / run / sub / "eval_test" / "eval_results.json"
    if not path.exists():
        return None, None
    rows = [r for r in json.loads(path.read_text())["results"] if r["round"] == rnd]
    if not rows:
        return None, None
    agents = sorted({r["agent"] for r in rows}, key=lambda s: int(s.split("-")[1]))
    marks = sorted({r["benchmark"] for r in rows})
    M = np.full((len(agents), len(marks)), np.nan)
    for r in rows:
        M[agents.index(r["agent"]), marks.index(r["benchmark"])] = r["mean_nll"]
    best = min(itertools.permutations(range(len(agents))),
               key=lambda p: sum(M[i, p[i]] for i in range(len(agents))))
    own = np.array([M[i, best[i]] for i in range(len(agents))])
    off = np.ones_like(M, dtype=bool)
    for i in range(len(agents)):
        off[i, best[i]] = False
    return float(own.mean()), float(M[off].mean())


