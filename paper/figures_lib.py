# ------------------------------------------------- seeds and derived quantities
def seeds_for(run: str) -> list[str]:
    """Scored data-split replicates of one arm, ``seed0`` first.

    Only subdirectories matching :data:`SEED_RE` that actually carry routing
    diagnostics are returned, so an in-flight replicate is skipped until it has
    been scored rather than showing up as a hole in a mean.
    """
    base = RESULTS / run
    if not base.is_dir():
        return []
    found = [
        d.name for d in base.iterdir()
        if d.is_dir() and SEED_RE.match(d.name)
        and (d / "routing_ensemble_diagnostics.json").is_file()
    ]
    return sorted(found, key=lambda s: (s != "seed0", s))


def contrast(flat: dict) -> dict:
    """Within-split contrasts from one diagnostics blob.

    Absolute NLL is not comparable across data splits -- each has its own test
    pool and its own generalist -- so every cross-split figure is built from
    these differences rather than from the raw numbers.
    """
    pooled = flat["pooled_nll"]
    learned = flat["learned_routing_nll"]
    oracle = flat["oracle_routing_nll"]
    envelope = pooled - oracle
    out = {
        "pooled": pooled, "learned": learned, "oracle": oracle,
        "gain": pooled - learned, "envelope": envelope,
        "capture": (pooled - learned) / envelope if envelope else float("nan"),
        "agreement": flat.get("routing_agreement_argmax"),
    }
    # Present only on runs scored after the ensemble metrics were added.
    for key in ("ensemble_mixture_nll", "ensemble_uniform_nll", "mean_tokens"):
        if flat.get(key) is not None:
            out[key] = flat[key]
    if "ensemble_mixture_nll" in out:
        out["gain_mixture"] = pooled - out["ensemble_mixture_nll"]
    if "ensemble_uniform_nll" in out:
        out["gain_uniform"] = pooled - out["ensemble_uniform_nll"]
    return out


def summarise(xs) -> tuple[float, float, int]:
    """Mean, sample standard deviation and count. SD is 0.0 for a single run."""
    a = np.asarray([x for x in xs if x is not None], dtype=float)
    if a.size == 0:
        return float("nan"), 0.0, 0
    return float(a.mean()), (float(a.std(ddof=1)) if a.size > 1 else 0.0), int(a.size)


def sigma_contrasts() -> dict[float, list[dict]]:
    """``{sigma_fraction: [contrast per scored split]}`` over the sweep."""
    out: dict[float, list[dict]] = {}
    for factor, run in SIGMA_ARMS:
        rows: list[dict] = []
        seen: set[str] = set()
        for candidate in SIGMA_RUN_ALIASES.get(factor, [run]):
            for sub in seeds_for(candidate):
                if sub in seen:          # one split, one row, whatever it is called
                    continue
                d = diagnostics(candidate, sub)
                if d is not None:
                    seen.add(sub)
                    rows.append(dict(contrast(d), seed=sub, run=candidate))
        if rows:
            out[factor] = sorted(rows, key=lambda r: (r["seed"] != "seed0", r["seed"]))
    return out


def roughness(ys) -> float:
    """Mean absolute second difference of a curve: how much it zigzags.

    The obvious summary of "does this sweep behave itself" is the standard
    deviation across reach, but SD answers the wrong question whenever the
    quantity has a genuine trend. The sequence-level mixture gain rises
    monotonically with reach under BOTH initialisations -- softer allocation
    mixes better even though it selects worse -- so its SD is ~0.0156 either
    way and reports no difference at all, while the two curves plainly differ.

    The second difference annihilates any straight line, so this measures
    departure from a smooth trend rather than departure from a constant, and
    separates the curves on both metrics. Points are assumed ordered by reach
    and are treated as equally spaced, which they are not (the sweep is denser
    near 0.5); that biases the statistic toward the closely spaced middle
    equally for every curve being compared, so ratios are meaningful and
    absolute values are not.
    """
    a = np.asarray([y for y in ys if y is not None], dtype=float)
    if a.size < 3:
        return float("nan")
    return float(np.abs(np.diff(a, 2)).mean())


def monotone_steps(ys) -> tuple[int, int]:
    """Rising and falling step counts of a curve, as a companion to roughness."""
    a = np.asarray([y for y in ys if y is not None], dtype=float)
    d = np.diff(a)
    return int((d > 0).sum()), int((d < 0).sum())


def theory_eq_sigma_contrasts() -> dict[str, dict[float, dict]]:
    """``{split: {sigma_fraction: contrast}}`` for the equilibrium reach sweep.

    Keyed by split first because the paired naive-vs-equilibrium comparison is
    only valid within a split, and the two splits are at different stages of
    completion.
    """
    out: dict[str, dict[float, dict]] = {}
    for factor, by_split in THEORY_EQ_SIGMA_ARMS.items():
        for split, run in by_split.items():
            d = diagnostics(run, "seed0")
            if d is not None:
                out.setdefault(split, {})[factor] = dict(
                    contrast(d), run=run, split=split)
    return out


def naive_sigma_contrasts() -> dict[str, dict[float, dict]]:
    """The naive reach sweep in the same shape, for paired differencing."""
    out: dict[str, dict[float, dict]] = {}
    for factor, rows in sigma_contrasts().items():
        for row in rows:
            out.setdefault(row["seed"], {})[factor] = row
    return out


