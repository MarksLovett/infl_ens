def true_theory(run: str) -> dict | None:
    """Theory positions re-solved against the *empirical* resource measure.

    The shipped ``B(b)`` is not a KDE of the prompt cloud: ``_kde_on_grid``
    divides each grid point's density by its own nearest-prompt kernel value, so
    a single prompt returns a uniform vector. What the solve actually optimised
    against is close to a uniform prior over the ``{0,0.5,1}^7`` lattice. Those
    positions are still the ones every run started from, so they are reported as
    the *approximate* initialisation; these are where the same solve lands when
    it sees the real distribution.

    Written by ``paper/true_theory_positions.py`` (CPU, minutes per arm) and
    cached, so figures never pay for the solve. Returns ``None`` until it runs.
    """
    path = DATA / "true_theory_positions.json"
    if not path.is_file():
        return None
    store = json.loads(path.read_text(encoding="utf-8"))
    entry = store.get(run)
    if not entry or not entry.get("pair_positions"):
        return None
    # The solve keys pairs by member, e.g. "pair_clone-0_clone-1"; order by the
    # first member so the ordering is stable. Identity across solves is
    # established by Hungarian matching, not by this order.
    def _first_index(name: str) -> int:
        found = re.findall(r"\d+", name)
        return int(found[0]) if found else 0

    names = sorted(entry["pair_positions"], key=_first_index)
    out = dict(entry)
    out["names"] = names
    out["positions"] = np.array([entry["pair_positions"][n] for n in names],
                                dtype=float)
    return out


def drift_stats(run: str, sub: str = "seed0") -> dict | None:
    """How far one run's pairs moved from the theory solve, and in what sense.

    The theory initialisation is a prediction made from a KDE-weighted lattice
    model of the prompt cloud; the final positions are what routed training
    produced. The difference is the only place the landscape model gets corrected
    by data, so it is reported rather than discarded.

    ``kept_dominant`` asks whether a pair's argmax axis is still the one the
    solve assigned it -- a cheap check on whether the theory's *assignment*, as
    opposed to its geometry, survived training.
    """
    h = history_slim(run, sub)
    if h is None or h.get("theory_positions") is None:
        return None
    theory = np.asarray(h["theory_positions"], dtype=float)
    final = np.asarray(h["positions"][-1], dtype=float)
    drift = final - theory
    dom_theory = np.asarray(h["dominant_axis"])
    own = np.array([drift[i, d] if d >= 0 else np.nan
                    for i, d in enumerate(dom_theory)])
    out = {
        "run": run, "seed": sub, "n_pairs": int(len(final)),
        "l2": np.linalg.norm(drift, axis=1),
        "mean_l2": float(np.linalg.norm(drift, axis=1).mean()),
        "per_axis": drift.mean(axis=0),
        "radius_theory": mean_radius(theory),
        "radius_final": mean_radius(final),
        "own_axis_drift": float(np.nanmean(own)),
        "kept_dominant": int((dom_theory == final.argmax(axis=1)).sum()),
    }

    # Distance to the solve that saw the real prompt distribution. Pair index is
    # not an identity across two separate solves, so match before differencing.
    tt = true_theory(run) if sub == "seed0" else None
    if tt is not None and len(tt["positions"]) == len(final):
        perm, cost = match_pairs(final, tt["positions"])
        matched = tt["positions"][perm]
        d_true = np.linalg.norm(final - matched, axis=1)
        out.update({
            "true_positions": matched,
            "l2_true": d_true,
            "mean_l2_true": float(d_true.mean()),
            "radius_true": mean_radius(matched),
            "match_cost_true": float(cost),
            "sigma0_lattice": tt.get("sigma0_lattice"),
            "sigma0_empirical": tt.get("sigma0_empirical"),
        })
        # How far apart the two solves are. This is the scale the trained drift
        # should be read against: moving 0.24 from the approximate solve means
        # something different if the two solves are 0.05 apart than if they are 0.4.
        perm_t, _ = match_pairs(theory, tt["positions"])
        out["theory_gap"] = float(
            np.linalg.norm(theory - tt["positions"][perm_t], axis=1).mean())
    return out


def better(ax, axis: str = "y", direction: str = "up",
           newline: bool = False) -> None:
    """Say which way is an improvement, in the axis label itself.

    Half of these axes are NLL differences and half are raw NLL, so the good
    direction flips from figure to figure and is not guessable from the label.
    Putting the arrow in the label rather than in a floating annotation keeps it
    from colliding with the data, which is how the first pass got it wrong.

    Pass ``newline`` when the label is already long enough to overrun its own
    axis; the arrow then sits on a second line instead of being clipped.
    """
    arrow = r"$\uparrow$" if direction == "up" else r"$\downarrow$"
    get, put = ((ax.get_ylabel, ax.set_ylabel) if axis == "y"
                else (ax.get_xlabel, ax.set_xlabel))
    current = get()
    if "better" in current:
        return
    sep = "\n" if newline else "  "
    put((current + sep if current else "") + "({} better)".format(arrow))


def save(fig, name: str, meta: dict | None = None, dpi: int = 300) -> Path:
    """Write one figure as vector PDF, raster PNG, and a provenance sidecar.

    The PDF is what ``main.tex`` includes. The PNG is what the explanatory
    artifact embeds, so both come from one render and cannot drift. The JSON
    sidecar records which runs and seeds went in, so a figure can always be
    traced back to its inputs.
    """
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.pdf"
    fig.savefig(path)
    fig.savefig(OUT / f"{name}.png", dpi=dpi)
    plt.close(fig)
    if meta is not None:
        payload = dict(meta)
        payload["generated"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
        (OUT / f"{name}.json").write_text(
            json.dumps(payload, indent=2, sort_keys=True, default=str),
            encoding="utf-8",
        )
    print(f"  wrote {path.relative_to(REPO)} (+.png{'' if meta is None else ' +.json'})")
    return path


